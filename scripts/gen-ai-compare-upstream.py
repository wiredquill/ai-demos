"""Generate charts/ai-compare-upstream from charts/ai-compare.

ai-compare (SUSE images) and ai-compare-upstream (community images) are the same
chart with a different default edition. They are published as two charts so the
Rancher Apps catalog offers each as its own app, which lets both run on one
cluster for a side-by-side comparison. Only charts/ai-compare is edited by hand;
this script rewrites the upstream copy, and CI checks it is up to date.

Usage: python3 scripts/gen-ai-compare-upstream.py [repo root]
"""
import os
import shutil
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else "."
SRC = os.path.join(ROOT, "charts", "ai-compare")
DST = os.path.join(ROOT, "charts", "ai-compare-upstream")
NOTICE = "Generated by scripts/gen-ai-compare-upstream.py from charts/ai-compare - edit there and re-run."


def rewrite(path, replacements, header=None):
    with open(path) as f:
        text = f.read()
    for old, new in replacements:
        if text.count(old) != 1:
            sys.exit(f"{path}: expected exactly one {old!r}")
        text = text.replace(old, new)
    if header:
        text = header + text
    with open(path, "w") as f:
        f.write(text)


shutil.rmtree(DST, ignore_errors=True)
shutil.copytree(SRC, DST, ignore=shutil.ignore_patterns("charts", "Chart.lock", "*.tgz"))

rewrite(
    os.path.join(DST, "Chart.yaml"),
    [
        ("name: ai-compare\n", "name: ai-compare-upstream\n"),
        ("catalog.cattle.io/display-name: AI Compare (SUSE)", "catalog.cattle.io/display-name: AI Compare (Upstream)"),
        (
            "description: AI Compare (SUSE) - compares direct Ollama answers with pipeline-enhanced Open WebUI answers on SUSE Application Collection and SUSE BCI images,",
            "description: AI Compare (Upstream) - compares direct Ollama answers with pipeline-enhanced Open WebUI answers on community images (ollama/ollama, ghcr.io/open-webui),",
        ),
        (
            "ai-compare-upstream is the same app on community images.",
            "ai-compare is the same app on SUSE Application Collection and SUSE BCI images.",
        ),
    ],
    header=f"# {NOTICE}\n",
)
rewrite(os.path.join(DST, "values.yaml"), [("\nedition: suse\n", "\nedition: upstream\n")], header=f"# {NOTICE}\n")
rewrite(os.path.join(DST, "questions.yaml"), [], header=f"# {NOTICE}\n")
rewrite(
    os.path.join(DST, "README.md"),
    [("# AI Compare\n", "# AI Compare (Upstream)\n")],
    header=f"<!-- {NOTICE} -->\n",
)
print(f"wrote {DST}")
